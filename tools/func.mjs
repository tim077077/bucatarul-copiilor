import { createRequire } from 'node:module';
const { chromium } = createRequire('/opt/node22/lib/node_modules/')('playwright');
import { spawn } from 'node:child_process';
const srv = spawn('npx', ['astro', 'preview', '--port', '4334'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch(); const p = await b.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:4334/', { waitUntil: 'networkidle' });
await p.click('#hero-board-tab-marti');
console.log('click Ma -> visible panel:', await p.locator('#hero-board [role=tabpanel]:not([hidden])').getAttribute('id'));
await p.keyboard.press('ArrowRight');
console.log('ArrowRight -> focused:', await p.evaluate(() => document.activeElement.id), 'selected:', await p.locator('#hero-board [aria-selected=true]').getAttribute('id'));
await p.click('#cerere [data-submit]');
console.log('empty submit -> status:', await p.locator('#cerere [data-status]').textContent(), '| invalid fields:', await p.locator('#cerere .field.is-invalid').count());
await p.fill('#cerere-nume', 'Test'); await p.fill('#cerere-inst', 'Grădinița Test'); await p.fill('#cerere-nr', '40'); await p.fill('#cerere-tel', '0743 064 433'); await p.check('#cerere input[name=gdpr]');
await p.click('#cerere [data-submit]');
console.log('valid submit (no key) -> status:', await p.locator('#cerere [data-status]').textContent());
await p.goto('http://localhost:4334/meniu', { waitUntil: 'networkidle' });
await p.click('a[href="/contact"].btn');
await p.waitForURL('**/contact'); console.log('view-transition nav ->', p.url(), '| form ready:', await p.locator('#oferta').getAttribute('data-ready'));
console.log('page errors:', errs.length ? errs : 'none');
await b.close(); srv.kill();
